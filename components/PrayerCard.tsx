import React, { useState, useRef, useEffect } from 'react';
import { Prayer, JournalEntry } from '../types';
import { BookmarkIcon, TrashIcon, PencilSquareIcon, PlusIcon, SpeakerWaveIcon, StopIcon, XMarkIcon, ClipboardDocumentIcon, CheckIcon, ArrowDownTrayIcon } from '@heroicons/react/24/outline';
import { BookmarkIcon as BookmarkSolidIcon, BoltIcon, HeartIcon } from '@heroicons/react/24/solid';

interface PrayerCardProps {
  prayer: Prayer;
  isSaved?: boolean;
  onSave?: (prayer: Prayer) => void;
  onDelete?: (id: string) => void;
  onUpdate?: (prayer: Prayer) => void;
}

const VOICES = [
  { name: 'Father (Deep)', id: 'Fenrir' },
  { name: 'Mother (Gentle)', id: 'Kore' },
  { name: 'Spirit (Soft)', id: 'Puck' },
  { name: 'Sage (Wise)', id: 'Zephyr' },
];

function decodeBase64(base64: string) {
  const binaryString = atob(base64);
  const bytes = new Uint8Array(binaryString.length);
  for (let i = 0; i < binaryString.length; i++) {
    bytes[i] = binaryString.charCodeAt(i);
  }
  return bytes;
}

async function decodePCM(data: Uint8Array, ctx: AudioContext, sampleRate: number): Promise<AudioBuffer> {
  const dataInt16 = new Int16Array(data.buffer);
  const buffer = ctx.createBuffer(1, dataInt16.length, sampleRate);
  const channelData = buffer.getChannelData(0);
  for (let i = 0; i < dataInt16.length; i++) {
    channelData[i] = dataInt16[i] / 32768.0;
  }
  return buffer;
}

export const PrayerCard: React.FC<PrayerCardProps> = ({ prayer, isSaved, onSave, onDelete, onUpdate }) => {
  const [showJournal, setShowJournal] = useState(false);
  const [newJournalEntry, setNewJournalEntry] = useState('');
  const [audioLoading, setAudioLoading] = useState(false);
  const [playingLang, setPlayingLang] = useState<string | null>(null);
  const [selectedVoice, setSelectedVoice] = useState('Fenrir');
  const [copiedSection, setCopiedSection] = useState<string | null>(null);
  
  const audioContextRef = useRef<AudioContext | null>(null);
  const sourceNodeRef = useRef<AudioBufferSourceNode | null>(null);

  useEffect(() => {
    return () => stopAudio();
  }, []);

  const stopAudio = () => {
    if (sourceNodeRef.current) {
      try {
        sourceNodeRef.current.onended = null;
        sourceNodeRef.current.stop();
      } catch (e) {}
      sourceNodeRef.current = null;
    }
    try { window.speechSynthesis?.cancel(); } catch (e) {}
    setPlayingLang(null);
    setAudioLoading(false);
  };

  const playAudio = async (text: string, language: string) => {
    if (playingLang === language) {
      stopAudio();
      return;
    }

    stopAudio();
    setAudioLoading(true);
    setPlayingLang(language);

    try {
      const synth = window.speechSynthesis;
      if (!synth) throw new Error("Voice is not available in this browser.");
      const u = new SpeechSynthesisUtterance(text);
      u.lang = language.toLowerCase().includes('english') ? 'en-US' : 'it-IT';
      u.rate = selectedVoice === 'Fenrir' ? 0.8 : 0.9;
      u.pitch = selectedVoice === 'Fenrir' ? 0.6 : selectedVoice === 'Kore' ? 1.2 : selectedVoice === 'Puck' ? 1.4 : 1;
      u.onend = () => { setPlayingLang(null); setAudioLoading(false); };
      u.onerror = () => { setPlayingLang(null); setAudioLoading(false); };
      synth.cancel();
      synth.speak(u);
      setAudioLoading(false);
    } catch (error: any) {
      stopAudio();
    }
  };

  const downloadAsTxt = () => {
    const content = `TITLE: ${prayer.title.toUpperCase()}
INTENTION: ${prayer.topic}
CREATED: ${new Date(prayer.createdAt).toLocaleString()}
CATEGORIES: ${prayer.categories.join(', ')}

=======================================================
ENGLISH REVELATION
=======================================================
${prayer.englishText}

=======================================================
LATIN REVELATION
=======================================================
${prayer.latinText}

=======================================================
ITALIAN REVELATION
=======================================================
${prayer.italianText}

-------------------------------------------------------
Generated by Jesus Christ of Atlantis Prayer Book
=======================================================`;

    navigator.clipboard?.writeText(content).catch(() => {});
    setCopiedSection('all');
    setTimeout(() => setCopiedSection(null), 2000);
  };

  const handleShareX = (text: string, label: string) => {
    const shareText = `Divine ${label} Prayer for: ${prayer.topic}\n\n"${text.substring(0, 180)}..."\n\n`;
    const url = `https://x.com/intent/tweet?text=${encodeURIComponent(shareText)}&hashtags=JesusChristofAtlantis`;
    window.open(url, '_blank');
  };

  const handleCopy = (text: string, section: string) => {
    navigator.clipboard.writeText(text);
    setCopiedSection(section);
    setTimeout(() => setCopiedSection(null), 2000);
  };

  const handleAddJournal = () => {
    if (!newJournalEntry.trim() || !onUpdate) return;
    const entry: JournalEntry = { id: crypto.randomUUID(), timestamp: Date.now(), text: newJournalEntry };
    onUpdate({ ...prayer, journalEntries: [entry, ...(prayer.journalEntries || [])] });
    setNewJournalEntry('');
  };

  return (
    <div className="bg-white dark:bg-stone-900 rounded-xl shadow-2xl border border-stone-200 dark:border-stone-800 overflow-hidden transition-all duration-300">
      <div className="bg-stone-900 dark:bg-black text-stone-200 p-6 flex flex-col md:flex-row justify-between items-start md:items-center gap-4">
        <div>
          <h2 className="font-display font-bold text-2xl text-gold-500 mb-1 uppercase tracking-wider">{prayer.title}</h2>
          <div className="flex flex-wrap gap-2 text-xs font-sans uppercase tracking-widest text-stone-500">
            <span>Intention: {prayer.topic}</span>
            {prayer.categories.map(cat => <span key={cat} className="px-2 py-0.5 border border-stone-700 rounded text-stone-400">{cat}</span>)}
          </div>
        </div>
        
        <div className="flex items-center gap-4 w-full md:w-auto">
          <div className="flex-1 md:flex-none">
            <div className="flex items-center gap-1 text-[10px] text-gold-400 font-bold mb-1"><BoltIcon className="w-3 h-3" /> POWER</div>
            <div className="w-full md:w-24 h-1 bg-stone-800 rounded-full overflow-hidden">
              <div className="h-full bg-gold-500" style={{ width: `${prayer.metrics.power}%` }}></div>
            </div>
          </div>
          <div className="flex-1 md:flex-none">
            <div className="flex items-center gap-1 text-[10px] text-red-400 font-bold mb-1"><HeartIcon className="w-3 h-3" /> FAITH</div>
            <div className="w-full md:w-24 h-1 bg-stone-800 rounded-full overflow-hidden">
              <div className="h-full bg-red-500" style={{ width: `${prayer.metrics.faith}%` }}></div>
            </div>
          </div>
          <div className="flex gap-2 ml-4 border-l border-stone-800 pl-4 items-center">
            <button onClick={downloadAsTxt} className="p-2 hover:text-gold-500 transition-colors" title="Copy full prayer">
              <ArrowDownTrayIcon className="w-5 h-5" />
            </button>
            {onSave && (
              <button onClick={() => onSave(prayer)} className="p-2 hover:text-gold-500 transition-colors" title={isSaved ? "Saved to Archive" : "Save to Archive"}>
                {isSaved ? <BookmarkSolidIcon className="w-5 h-5 text-gold-500" /> : <BookmarkIcon className="w-5 h-5" />}
              </button>
            )}
            {onDelete && <button onClick={() => onDelete(prayer.id)} className="p-2 hover:text-red-500 transition-colors" title="Delete Prayer"><TrashIcon className="w-5 h-5" /></button>}
          </div>
        </div>
      </div>

      <div className="bg-stone-50 dark:bg-stone-900/50 border-b border-stone-200 dark:border-stone-800 px-6 py-2 flex items-center justify-end gap-2">
        <span className="text-[10px] font-sans text-stone-400 uppercase tracking-widest">Divine Voice:</span>
        <select value={selectedVoice} onChange={(e) => setSelectedVoice(e.target.value)} className="bg-transparent text-xs font-bold text-stone-600 dark:text-stone-300 border-none outline-none focus:ring-0 cursor-pointer">
          {VOICES.map(v => <option key={v.id} value={v.id} className="dark:bg-stone-900">{v.name}</option>)}
        </select>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-3 divide-y md:divide-y-0 md:divide-x divide-stone-100 dark:divide-stone-800">
        {[
          { label: 'English', text: prayer.englishText, lang: 'English' },
          { label: 'Latin', text: prayer.latinText, lang: 'Latin' },
          { label: 'Italian', text: prayer.italianText, lang: 'Italian' }
        ].map((sec, idx) => (
          <div key={idx} className={`p-6 md:p-8 relative min-h-[280px] pb-16 ${idx === 1 ? 'bg-stone-50/50 dark:bg-stone-800/20' : ''}`}>
            <div className="flex justify-between items-center mb-6">
              <span className="text-[10px] font-bold text-stone-400 uppercase tracking-widest">{sec.label}</span>
              <button 
                onClick={() => playAudio(sec.text, sec.lang)} 
                disabled={audioLoading && playingLang !== sec.lang} 
                className={`p-2 rounded-full transition-all ${playingLang === sec.lang ? 'bg-gold-100 text-gold-600 animate-pulse' : 'text-stone-300 hover:text-gold-500 dark:hover:bg-stone-800'}`}
                title={playingLang === sec.lang ? "Stop recitation" : "Recite prayer"}
              >
                {playingLang === sec.lang ? <StopIcon className="w-4 h-4" /> : <SpeakerWaveIcon className="w-4 h-4" />}
              </button>
            </div>
            <p className={`text-lg leading-relaxed text-stone-800 dark:text-stone-200 ${sec.label === 'Latin' ? 'font-display italic' : 'font-serif'}`}>
              {sec.text.split('\n').map((l, i) => <React.Fragment key={i}>{l}<br/></React.Fragment>)}
            </p>
            
            <div className="absolute bottom-4 right-4 flex gap-2">
              <button onClick={() => handleShareX(sec.text, sec.label)} className="p-2 text-stone-300 hover:text-sky-400 transition-colors" title={`Share ${sec.label} prayer to X`}>
                <svg className="w-4 h-4 fill-current" viewBox="0 0 24 24"><path d="M18.244 2.25h3.308l-7.227 8.26 8.502 11.24H16.17l-5.214-6.817L4.99 21.75H1.68l7.73-8.835L1.254 2.25H8.08l4.713 6.231zm-1.161 17.52h1.833L7.084 4.126H5.117z"></path></svg>
              </button>
              <button onClick={() => handleCopy(sec.text, sec.label)} className="p-2 text-stone-300 hover:text-gold-500 transition-colors" title={`Copy ${sec.label} text`}>
                {copiedSection === sec.label ? <CheckIcon className="w-4 h-4 text-green-500" /> : <ClipboardDocumentIcon className="w-4 h-4" />}
              </button>
            </div>
          </div>
        ))}
      </div>

      <div className="border-t border-stone-100 dark:border-stone-800">
        <button onClick={() => setShowJournal(!showJournal)} className="w-full p-4 flex items-center justify-center gap-2 text-[10px] font-bold uppercase tracking-widest text-stone-400 hover:text-gold-600 transition-colors">
          <PencilSquareIcon className="w-4 h-4" /> {showJournal ? "Close Reflection" : `Reflections (${prayer.journalEntries?.length || 0})`}
        </button>
        {showJournal && (
          <div className="p-6 bg-stone-50/30 dark:bg-black/20 border-t border-stone-100 dark:border-stone-800">
            <div className="flex gap-2 mb-6">
              <input type="text" value={newJournalEntry} onChange={(e) => setNewJournalEntry(e.target.value)} placeholder="Record your divine realization..." className="flex-1 p-3 rounded-lg border border-stone-200 dark:border-stone-700 bg-white dark:bg-stone-800 text-sm focus:ring-1 focus:ring-gold-500 outline-none" onKeyDown={(e) => e.key === 'Enter' && handleAddJournal()} />
              <button onClick={handleAddJournal} disabled={!newJournalEntry.trim()} className="p-3 bg-gold-500 text-white rounded-lg hover:bg-gold-600 disabled:opacity-50"><PlusIcon className="w-5 h-5" /></button>
            </div>
            <div className="space-y-4 max-h-48 overflow-y-auto">
              {prayer.journalEntries?.map(entry => (
                <div key={entry.id} className="p-3 bg-white dark:bg-stone-800 rounded border border-stone-100 dark:border-stone-700 relative group">
                  <p className="text-sm italic font-serif text-stone-600 dark:text-stone-400">"{entry.text}"</p>
                  <span className="text-[9px] text-stone-400">{new Date(entry.timestamp).toLocaleDateString()}</span>
                </div>
              ))}
            </div>
          </div>
        )}
      </div>
    </div>
  );
};