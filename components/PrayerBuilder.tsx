
import React from 'react';
import { SparklesIcon, ArchiveBoxIcon, TrashIcon, ArrowDownTrayIcon, HeartIcon, ShieldCheckIcon, SunIcon, UserGroupIcon, BanknotesIcon, ScaleIcon, FaceSmileIcon, LightBulbIcon } from '@heroicons/react/24/outline';
import { Prayer } from '../types';
import { PrayerCard } from './PrayerCard';
import { LoadingState } from './LoadingState';

interface PrayerBuilderProps {
  topic: string;
  setTopic: (t: string) => void;
  loading: boolean;
  currentPrayer: Prayer | null;
  setCurrentPrayer: (p: Prayer | null) => void;
  savedPrayers: Prayer[];
  showArchive: boolean;
  setShowArchive: (s: boolean) => void;
  handleGenerate: (e?: React.FormEvent) => void;
  savePrayer: (p: Prayer) => void;
  deletePrayer: (id: string) => void;
  updatePrayer: (p: Prayer) => void;
  prayerLength: 'short' | 'medium' | 'long';
  setPrayerLength: (l: 'short' | 'medium' | 'long') => void;
  setShowLiveTranscriber: (s: boolean) => void;
  prayerCredits?: number;
  isFree?: boolean;
  genError?: string | null;
}

const INTENTIONS = [
  { label: 'Healing', text: 'Healing for my body and mind', I: HeartIcon },
  { label: 'Protection', text: 'Protection for my family and home', I: ShieldCheckIcon },
  { label: 'Gratitude', text: 'Gratitude for this day', I: SunIcon },
  { label: 'Guidance', text: 'Guidance on my next step', I: LightBulbIcon },
  { label: 'Abundance', text: 'Abundance and provision', I: BanknotesIcon },
  { label: 'Peace', text: 'Peace in a troubled heart', I: FaceSmileIcon },
  { label: 'Forgiveness', text: 'Forgiveness and release', I: ScaleIcon },
  { label: 'Family', text: 'Unity and blessing for my family', I: UserGroupIcon },
];

export const PrayerBuilder: React.FC<PrayerBuilderProps> = ({
  topic, setTopic, loading, currentPrayer, setCurrentPrayer, savedPrayers,
  showArchive, setShowArchive, handleGenerate, savePrayer, deletePrayer, updatePrayer,
  prayerLength, setPrayerLength, setShowLiveTranscriber, prayerCredits = 0, isFree = false, genError
}) => {
  const n = savedPrayers.length;
  const avg = (k: 'power' | 'faith') => n ? Math.round(savedPrayers.reduce((a, p) => a + (p.metrics?.[k] || 0), 0) / n) : 0;
  const catCount: Record<string, number> = {};
  savedPrayers.forEach(p => (p.categories || []).forEach(c => { catCount[c] = (catCount[c] || 0) + 1; }));
  const topCat = Object.entries(catCount).sort((a, b) => b[1] - a[1])[0]?.[0] || '—';
  const stats = [
    { v: String(n), l: 'Prayers composed' },
    { v: n ? `${avg('power')}%` : '—', l: 'Avg. power' },
    { v: n ? `${avg('faith')}%` : '—', l: 'Avg. faith' },
    { v: topCat, l: 'Most prayed for' },
  ];
  const idle = !showArchive && !currentPrayer && !loading;
  const downloadPrayerAsTxt = (p: Prayer) => {
    const content = `TITLE: ${p.title.toUpperCase()}
INTENTION: ${p.topic}
CREATED: ${new Date(p.createdAt).toLocaleString()}
CATEGORIES: ${p.categories.join(', ')}

=======================================================
ENGLISH REVELATION
=======================================================
${p.englishText}

=======================================================
LATIN REVELATION
=======================================================
${p.latinText}

=======================================================
ITALIAN REVELATION
=======================================================
${p.italianText}

-------------------------------------------------------
Generated by Jesus Christ of Atlantis Prayer Book
=======================================================`;

    navigator.clipboard?.writeText(content).catch(() => {});
  };

  return (
    <div className="animate-fade-in max-w-5xl mx-auto flex flex-col justify-start min-h-[calc(100vh-120px)] pt-10 md:pt-20 pb-28 md:pb-20 px-4 md:px-6">
      <div className="text-center mb-8">
        <h2 className="font-display text-4xl sm:text-6xl font-bold mb-3 text-stone-900 dark:text-stone-100 tracking-widest uppercase leading-tight">PRAYER BOOK</h2>
        <p className="font-serif italic text-base sm:text-xl text-stone-500 dark:text-stone-400 px-4">Compose personalized invocations through the Atlantean Blueprint</p>
        
        <div className="mt-6 inline-flex flex-wrap items-center justify-center gap-x-3 gap-y-1 px-5 py-3 rounded-3xl border border-gold-500/40 bg-gold-500/10 text-[11px] md:text-xs font-bold uppercase tracking-widest text-gold-700 dark:text-gold-400">
          {isFree ? <span>Editor access: prayers are free for you</span> : prayerCredits > 0
            ? <span>{prayerCredits} prayer credit{prayerCredits > 1 ? 's' : ''} ready</span>
            : <><span className="font-display text-base mr-2">$1</span><span>per prayer · a donation via PayPal</span></>}
        </div>

        <div className="mt-6 md:mt-10 flex justify-center gap-4">
           <button 
            onClick={() => setShowArchive(!showArchive)}
            className={`flex items-center gap-3 px-6 md:px-10 py-3 md:py-4 rounded-full text-[9px] md:text-[10px] font-bold uppercase tracking-[0.3em] transition-all shadow-lg ${showArchive ? 'bg-gold-500 text-white shadow-gold-500/20' : 'bg-stone-100 dark:bg-stone-800 text-stone-500'}`}
          >
            <ArchiveBoxIcon className="w-5 h-5" />
            {showArchive ? 'Close Library' : `Divine Archive (${savedPrayers.length})`}
          </button>
        </div>

        {!showArchive && (
          <form onSubmit={handleGenerate} className="mt-10 md:mt-12 max-w-3xl mx-auto space-y-6 md:space-y-8 animate-fade-in">
            <div className="relative group">
              <div className="absolute -inset-1 bg-gradient-to-r from-gold-500 to-amber-500 rounded-full blur opacity-25 group-hover:opacity-40 transition duration-1000 group-hover:duration-200"></div>
              <input 
                type="text" 
                value={topic} 
                onChange={(e) => setTopic(e.target.value)} 
                placeholder="What intention?" 
                className="relative w-full p-5 md:p-8 pr-28 md:pr-36 rounded-full border border-stone-200 dark:border-stone-800 bg-white dark:bg-stone-900 text-lg md:text-2xl font-serif outline-none focus:ring-4 focus:ring-gold-500/10 shadow-2xl transition-all" 
                disabled={loading} 
              />
              <button 
                type="submit" 
                disabled={loading || !topic.trim()} 
                className="absolute right-2 md:right-4 top-2 bottom-2 md:top-4 md:bottom-4 bg-gold-500 hover:bg-gold-600 text-white rounded-full px-4 md:px-9 gap-2 flex items-center justify-center transition-all disabled:opacity-50 active:scale-95 shadow-lg"
              >
                <SparklesIcon className="w-5 h-5 md:w-7 md:h-7" />{!isFree && prayerCredits < 1 && <span className="font-bold text-sm md:text-lg">$1</span>}
              </button>
            </div>

            <div className="flex flex-col sm:flex-row justify-center items-center gap-4 md:gap-6">
              <div className="flex bg-stone-100 dark:bg-stone-800 p-1.5 md:p-2 rounded-full border border-stone-200 dark:border-stone-800 shadow-inner w-full sm:w-auto">
                {(['short', 'medium', 'long'] as const).map(l => (
                  <button key={l} type="button" onClick={() => setPrayerLength(l)} className={`flex-1 sm:flex-none px-6 md:px-10 py-2 md:py-3 text-[9px] md:text-[10px] font-bold uppercase tracking-widest rounded-full transition-all ${prayerLength === l ? 'bg-white dark:bg-stone-700 text-gold-600 dark:text-gold-400 shadow-md' : 'text-stone-400 hover:text-stone-600'}`}>{l}</button>
                ))}
              </div>
            </div>
            {genError && <p className="text-sm font-serif italic text-red-500">{genError}</p>}
            <div className="space-y-3">
              <p className="text-[10px] font-bold uppercase tracking-[0.25em] text-stone-400">Or start with an intention</p>
              <div className="flex flex-wrap justify-center gap-2">
                {INTENTIONS.map(i => (
                  <button key={i.label} type="button" onClick={() => setTopic(i.text)} className="inline-flex items-center gap-2 px-4 py-2.5 rounded-full border border-stone-200 dark:border-stone-800 bg-white/70 dark:bg-stone-900/70 text-xs font-bold text-stone-600 dark:text-stone-300 hover:border-gold-500 hover:text-gold-600 transition-colors">
                    <i.I className="w-4 h-4 text-gold-500" /> {i.label}
                  </button>
                ))}
              </div>
            </div>
          </form>
        )}
      </div>

      {idle && (
        <div className="space-y-8 md:space-y-10 max-w-4xl mx-auto w-full animate-fade-in">
          <div className="grid grid-cols-2 md:grid-cols-4 gap-3 md:gap-5">
            {stats.map(t => (
              <div key={t.l} className="p-4 md:p-6 rounded-3xl border border-stone-200 dark:border-stone-800 bg-white/80 dark:bg-stone-900/80 text-center">
                <div className="font-display text-xl md:text-3xl font-bold text-gold-500 truncate">{t.v}</div>
                <div className="text-[9px] md:text-[10px] font-bold uppercase tracking-widest text-stone-400 mt-1">{t.l}</div>
              </div>
            ))}
          </div>

          <div className="grid md:grid-cols-3 gap-3 md:gap-5">
            {[
              { n: '1', t: 'Name your intention', d: 'Type what you are praying for, or tap a starter above.' },
              { n: '2', t: 'Send $1 on PayPal', d: 'One dollar per prayer, donated through PayPal. It takes about 20 seconds.' },
              { n: '3', t: 'Receive your prayer', d: 'Written in English, Latin and Italian. Save it, copy it, or hear it spoken.' },
            ].map(x => (
              <div key={x.n} className="flex md:block items-start gap-4 p-5 md:p-6 rounded-3xl border border-stone-200 dark:border-stone-800 bg-white/80 dark:bg-stone-900/80 text-left">
                <span style={{ width: 36, height: 36, minWidth: 36 }} className="shrink-0 rounded-full bg-gold-500 text-black font-display font-bold flex items-center justify-center md:mb-4">{x.n}</span>
                <div><h4 className="font-display text-sm font-bold uppercase tracking-wide text-stone-800 dark:text-stone-100 mb-1">{x.t}</h4><p className="text-sm font-serif text-stone-500 dark:text-stone-400 leading-relaxed">{x.d}</p></div>
              </div>
            ))}
          </div>

          {savedPrayers.length > 0 && (
            <div className="space-y-3 text-left">
              <h4 className="font-display text-xs font-bold uppercase tracking-[0.2em] text-gold-500">Recent prayers</h4>
              <div className="grid sm:grid-cols-3 gap-3 md:gap-5">
                {savedPrayers.slice(0, 3).map(p => (
                  <button key={p.id} onClick={() => setCurrentPrayer(p)} className="text-left p-5 rounded-3xl border border-stone-200 dark:border-stone-800 bg-white/80 dark:bg-stone-900/80 hover:border-gold-500 transition-colors">
                    <h5 className="font-display text-sm font-bold uppercase tracking-wide text-stone-800 dark:text-stone-100 truncate">{p.title}</h5>
                    <p className="text-[10px] font-bold uppercase tracking-widest text-stone-400 mt-1 truncate">{p.topic}</p>
                    <p className="text-sm font-serif italic text-stone-500 dark:text-stone-400 line-clamp-3 mt-3">“{p.englishText}”</p>
                  </button>
                ))}
              </div>
            </div>
          )}
        </div>
      )}

      {loading && <LoadingState />}

      {currentPrayer && !showArchive && !loading && (
        <div className="mt-8 md:mt-12 px-2 md:px-4 max-w-4xl mx-auto w-full animate-fade-in">
          <PrayerCard 
            prayer={currentPrayer} 
            isSaved={savedPrayers.some(p => p.id === currentPrayer.id)} 
            onSave={savePrayer} 
            onDelete={deletePrayer} 
            onUpdate={updatePrayer} 
          />
        </div>
      )}

      {showArchive && (
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-6 md:gap-8 animate-fade-in px-2 md:px-4 mt-8">
          {savedPrayers.length > 0 ? savedPrayers.map(p => (
            <div key={p.id} className="bg-white dark:bg-stone-900 p-6 md:p-8 rounded-3xl border border-stone-200 dark:border-stone-800 shadow-xl group hover:border-gold-500 transition-all cursor-pointer flex flex-col justify-between" onClick={() => { setCurrentPrayer(p); setShowArchive(false); }}>
              <div>
                <h3 className="font-display font-bold text-xl md:text-2xl text-stone-800 dark:text-stone-100 mb-2 md:mb-3 truncate group-hover:text-gold-500 transition-colors uppercase tracking-tight">{p.title}</h3>
                <p className="text-[9px] md:text-[10px] text-stone-400 uppercase font-bold tracking-[0.2em] mb-4 md:mb-6 pb-2 border-b border-stone-100 dark:border-stone-800">{p.topic}</p>
                <p className="text-sm md:text-base font-serif italic text-stone-600 dark:text-stone-400 line-clamp-4 leading-relaxed">"{p.englishText}"</p>
              </div>
              <div className="flex justify-between items-center mt-6 md:mt-8 pt-4 md:pt-6 border-t border-stone-100 dark:border-stone-800">
                <span className="text-[9px] md:text-[10px] text-stone-400 font-bold">{new Date(p.createdAt).toLocaleDateString()}</span>
                <div className="flex gap-2">
                  <button onClick={(e) => { e.stopPropagation(); downloadPrayerAsTxt(p); }} className="p-1.5 md:p-2 text-stone-300 hover:text-gold-500 transition-colors" title="Download .txt">
                    <ArrowDownTrayIcon className="w-4 h-4 md:w-5 md:h-5" />
                  </button>
                  <button onClick={(e) => { e.stopPropagation(); deletePrayer(p.id); }} className="p-1.5 md:p-2 text-stone-300 hover:text-red-500 transition-colors" title="Delete Prayer">
                    <TrashIcon className="w-4 h-4 md:w-5 md:h-5" />
                  </button>
                </div>
              </div>
            </div>
          )) : (
            <div className="col-span-full py-24 text-center">
              <p className="text-stone-400 font-serif italic text-lg md:text-xl">"The library is silent. Your composed prayers will echo here once archived."</p>
            </div>
          )}
        </div>
      )}
    </div>
  );
};
